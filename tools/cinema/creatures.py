def make(model_id):
    s = dict(ANIMALS[model_id], name=model_id)
    kind = s.pop('coat_kind', None)
    if kind == 'skin':
        s['coat'] = M.skin(s['color'], 'coat')
    elif kind == 'scales':
        s['coat'] = M.scales(s['color'], s['color2'], 'coat', 0.5)
    return quadruped.build(s)


